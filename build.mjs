/**
 * Build the two browser artifacts of the paper reader from their sources:
 * `client.js` (the plugin entry: panel, viewer chrome, ask panel) and
 * `client.pdfjs.js` (a lazily required chunk that carries PDF.js, its worker,
 * and the font/CMap/wasm resources the engine needs to open real papers).
 *
 * The Web client loads a bundle as a classic script that hands a factory to
 * `window.__ModuleLoader__`; the factory receives the shared module table's
 * `require`, so `react` stays external while PDF.js is inlined into the chunk.
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const pdfjs = join(root, 'node_modules', 'pdfjs-dist')

/** Read one resource directory into a filename -> base64 map. */
function directoryAssets(directory) {
  const files = {}
  for (const name of readdirSync(directory)) {
    if (name.startsWith('LICENSE')) continue
    const path = join(directory, name)
    if (!statSync(path).isFile()) continue
    files[name] = readFileSync(path).toString('base64')
  }
  return files
}

// PDF.js fetches CMap, standard-font and wasm bytes through BinaryDataFactory;
// bundling them keeps opening a paper independent of network access.
const assets = {
  cMapUrl: directoryAssets(join(pdfjs, 'cmaps')),
  standardFontDataUrl: directoryAssets(join(pdfjs, 'standard_fonts')),
  wasmUrl: directoryAssets(join(pdfjs, 'wasm')),
}
const workerSource = readFileSync(join(pdfjs, 'build', 'pdf.worker.min.mjs'), 'utf8')

mkdirSync(join(root, 'src', 'pdf'), { recursive: true })
writeFileSync(
  join(root, 'src', 'pdf', 'assets.generated.js'),
  `/** Generated by build.mjs from pdfjs-dist; do not edit. */\nexport const workerSource = ${JSON.stringify(workerSource)}\nexport const assets = ${JSON.stringify(assets)}\n`,
)

// KaTeX ships its CSS with relative font files; inline the woff2 faces as data
// URLs so the lazily loaded chunk needs no extra asset route.
const katexDist = join(root, 'node_modules', 'katex', 'dist')
let katexCss = readFileSync(join(katexDist, 'katex.min.css'), 'utf8')
katexCss = katexCss.replace(
  /src:url\(fonts\/([^)]+?)\.woff2\) format\("woff2"\),url\(fonts\/[^)]+?\.woff\) format\("woff"\),url\(fonts\/[^)]+?\.ttf\) format\("truetype"\)/g,
  (match, name) => `src:url(data:font/woff2;base64,${readFileSync(join(katexDist, 'fonts', `${name}.woff2`)).toString('base64')}) format("woff2")`,
)
katexCss = katexCss.replace(
  /url\(fonts\/([^)]+?)\.woff2\)/g,
  (match, name) => `url(data:font/woff2;base64,${readFileSync(join(katexDist, 'fonts', `${name}.woff2`)).toString('base64')})`,
)
writeFileSync(
  join(root, 'src', 'pdf', 'katex.generated.js'),
  `/** Generated by build.mjs from katex; do not edit. */\nexport const katexCss = ${JSON.stringify(katexCss)}\n`,
)

const common = {
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  external: ['react', 'react-dom'],
  mainFields: ['browser', 'module', 'main'],
  conditions: ['browser'],
  define: { 'import.meta.url': '""' },
  logLevel: 'info',
}

mkdirSync(join(root, 'build'), { recursive: true })
await build({
  ...common,
  entryPoints: [join(root, 'src', 'client', 'index.js')],
  outfile: join(root, 'build', 'client-body.js'),
  minify: true,
  legalComments: 'eof',
})
await build({
  ...common,
  entryPoints: [join(root, 'src', 'pdf', 'index.js')],
  outfile: join(root, 'build', 'pdf-body.js'),
  minify: true,
  legalComments: 'eof',
})

/** Wrap a CommonJS body in the loader's factory shape and write the artifact. */
function wrap(source, target, id, chunk) {
  const body = readFileSync(join(root, 'build', source), 'utf8')
  const header = chunk === undefined
    ? `{id:${JSON.stringify(id)},factory(require){`
    : `{id:${JSON.stringify(id)},chunk:${JSON.stringify(chunk)},factory(require){`
  const artifact = `window.__ModuleLoader__.load(${header}var module={exports:{}};var exports=module.exports;\n${body}\n;return module.exports}});\n`
  writeFileSync(join(root, target), artifact)
  console.log(`${target}: ${(artifact.length / 1024).toFixed(0)} KiB`)
}

wrap('client-body.js', 'client.js', 'dsh-pdf-paper-reader')
wrap('pdf-body.js', 'client.pdfjs.js', 'dsh-pdf-paper-reader', 'client.pdfjs.js')
